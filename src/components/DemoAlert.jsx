// src/components/DemoAlert.jsx
import React, { useState } from 'react';
import { AlertTriangle, AlertOctagon, Info, Check, ShieldAlert, Clock } from 'lucide-react';

export default function DemoAlert({ alert, onDismiss }) {
  const [acknowledged, setAcknowledged] = useState(false);

  const getSeverityMeta = (severity) => {
    switch (severity?.toLowerCase()) {
      case 'critical':
        return {
          icon: AlertOctagon,
          badgeClass: 'badge-critical',
          accentColor: '#ef4444'
        };
      case 'warning':
        return {
          icon: AlertTriangle,
          badgeClass: 'badge-warning',
          accentColor: '#f97316'
        };
      case 'advisory':
      default:
        return {
          icon: Info,
          badgeClass: 'badge-advisory',
          accentColor: '#0ea5e9'
        };
    }
  };

  const meta = getSeverityMeta(alert.severity);
  const Icon = meta.icon;

  return (
    <div className={`demo-alert-card ${meta.badgeClass} ${acknowledged ? 'alert-acknowledged' : ''}`}>
      <div className="demo-alert-top">
        <div className="demo-alert-badge-group">
          <span className="demo-alert-tag">DEMO ALERT</span>
          <span className={`severity-chip ${meta.badgeClass}`}>{alert.severity}</span>
          {alert.category && <span className="category-chip">{alert.category}</span>}
        </div>
        <div className="alert-meta-time">
          <Clock size={13} />
          <span>{alert.timestamp || 'Simulated Feed'}</span>
        </div>
      </div>

      <div className="demo-alert-main">
        <div className="alert-icon-col" style={{ color: meta.accentColor }}>
          <Icon size={24} />
        </div>
        <div className="alert-text-col">
          <h4 className="alert-title">{alert.title}</h4>
          <p className="alert-message">{alert.message}</p>

          {alert.action && (
            <div className="alert-action-box">
              <span className="action-lead">Recommended Directive:</span>
              <p className="action-text">{alert.action}</p>
            </div>
          )}
        </div>
      </div>

      <div className="demo-alert-footer">
        <span className="demo-alert-footnote">
          * Automated notification generated by ClimateShield AI Simulation Framework
        </span>
        <button
          className={`ack-button ${acknowledged ? 'btn-acknowledged' : ''}`}
          onClick={() => setAcknowledged(!acknowledged)}
        >
          {acknowledged ? (
            <>
              <Check size={14} /> Acknowledged
            </>
          ) : (
            'Acknowledge Alert'
          )}
        </button>
      </div>
    </div>
  );
}

export function AlertsFeed({ alerts = [] }) {
  if (!alerts || alerts.length === 0) {
    return (
      <div className="empty-alerts-card">
        <div className="empty-alerts-icon">
          <ShieldAlert size={36} />
        </div>
        <h4>No Active Disaster Alerts</h4>
        <p>All monitored thresholds are currently in baseline range for this scenario.</p>
      </div>
    );
  }

  return (
    <div className="alerts-feed-stack">
      {alerts.map((alt) => (
        <DemoAlert key={alt.id} alert={alt} />
      ))}
    </div>
  );
}
